import os, sys
from dataclasses import asdict, replace
import pandas as pd
import streamlit as st

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from rag import llm, evals
from rag.kb import chunk_docs, parse_doc
from rag.config import UPLOAD_DIR
from rag.pipeline import KB, Config, PRESETS, run

st.set_page_config(page_title="AskTelco", page_icon="📡", layout="wide")
ROLES = {"Postpaid customer": "postpaid", "Prepaid customer": "prepaid", "NOC engineer (internal)": "noc"}
SAMPLES = [
    "How much data does Postpaid Max include?",
    "How much is the 10-day international roaming pack?",
    "What does error code E-4107 mean?",
    "What is the extension of the Level 2 Transport on-call?",
    "Which cafeteria serves vegan food on Fridays?",
    "Who owns the fibre link that caused the Chennai North outage INC-4471?",
    "What is the Global Roaming Weekend Offer?",
    "How much is the Student Plan?",
]
DIALS = ["metadata_filter", "chunking", "mode", "rewrite", "rerank", "multihop", "guard", "grounded_prompt", "scan_injection", "fixed_size"]

if "kb" not in st.session_state:
    st.session_state.kb = KB()
kb = st.session_state.kb


def load_preset():
    cfg = PRESETS[st.session_state["preset"]]
    for d in DIALS:
        st.session_state["d_" + d] = getattr(cfg, d)
    st.session_state["d_top_k"] = cfg.top_k


if "d_top_k" not in st.session_state:
    st.session_state["preset"] = "Full pipeline"
    load_preset()


def current_cfg():
    s = st.session_state
    return Config(**{d: s["d_" + d] for d in DIALS}, top_k=s["d_top_k"])


# ------------------------------------------------------------------ sidebar
with st.sidebar:
    st.title("📡 AskTelco")
    st.caption("NetNova Telecom knowledge assistant")
    mode_online = llm.online()
    (st.success if mode_online else st.warning)(f"Mode: {llm.mode_name()}" + ("" if mode_online else " (no API key: numbers will differ)"))
    who = st.selectbox("Who is asking?", list(ROLES))
    st.selectbox("Preset", list(PRESETS), key="preset", on_change=load_preset)
    with st.expander("Dials (change one at a time)", expanded=True):
        st.toggle("Metadata filter (role + current only)", key="d_metadata_filter")
        st.radio("Chunking", ["fixed", "section"], key="d_chunking", horizontal=True)
        st.radio("Search", ["vector", "keyword", "hybrid"], key="d_mode", horizontal=True)
        st.toggle("Query rewrite", key="d_rewrite")
        st.toggle("Reranker", key="d_rerank")
        st.toggle("Multi-hop (follow ids)", key="d_multihop")
        st.toggle("'I don't know' guard", key="d_guard")
        st.toggle("Strict prompt (rule 6)", key="d_grounded_prompt")
        st.toggle("Scan uploads for hidden instructions", key="d_scan_injection")
        st.slider("Top-k chunks", 1, 8, key="d_top_k")
        st.slider("Fixed chunk size (words)", 10, 120, key="d_fixed_size")
    st.caption(f"Knowledge base: {len(kb.docs)} documents")
    if st.button("🔄 Re-index from kb/ folder"):
        st.session_state.kb = KB()
        st.rerun()

role = ROLES[who]
tab_ask, tab_eval, tab_ing = st.tabs(["💬 Ask", "📊 Evals", "🧩 Ingestion"])


# ------------------------------------------------------------------ Ask
def show_result(title, r, cfg):
    st.subheader(title)
    if r.refused:
        st.warning(r.answer)
    else:
        st.info(r.answer)
    st.caption(f"{r.seconds}s  |  ${r.usd:.5f}  |  {len(r.sources)} chunks")
    if r.sources:
        df = pd.DataFrame([dict(doc=s["doc_id"], part=s["section"] or "(fixed)", status=s["status"],
                                visible_to=", ".join(s["roles"]), similarity=s["cos"], score=s["score"],
                                flagged="⚠️" if s["flagged"] else "") for s in r.sources])
        st.dataframe(df, hide_index=True)
        bad = [s for s in r.sources if s["status"] != "current"]
        leak = [s for s in r.sources if role not in s["roles"]]
        if bad:
            st.error(f"Used an OLD article: {', '.join(s['doc_id'] for s in bad)}")
        if leak:
            st.error(f"Showed content this user must not see: {', '.join(s['doc_id'] for s in leak)}")
        if any(s["flagged"] for s in r.sources):
            st.error("A document with hidden instructions reached the model.")
    with st.expander("What the pipeline did"):
        for t in r.trace:
            st.write("•", t)
        for s in r.sources:
            st.caption(f"{s['doc_id']}: {s['text'][:300]}")


with tab_ask:
    c1, c2 = st.columns([3, 1])
    pick = c1.selectbox("Example questions", ["(type your own below)"] + SAMPLES)
    compare = c2.checkbox("Compare with baseline", value=True)
    question = st.text_input("Your question", value="" if pick.startswith("(") else pick)
    if st.button("Ask", type="primary") and question:
        cfg = current_cfg()
        with st.spinner("Searching..."):
            main = run(kb, question, cfg, role)
            base = run(kb, question, PRESETS["Baseline"], role) if compare else None
        if compare:
            a, b = st.columns(2)
            with a:
                show_result("Baseline", base, PRESETS["Baseline"])
            with b:
                show_result("Your pipeline", main, cfg)
        else:
            show_result("Your pipeline", main, cfg)

# ------------------------------------------------------------------ Evals
with tab_eval:
    st.write(f"{len(evals.BASE_QUESTIONS)} built-in questions + {len(evals.MY_QUESTIONS)} of yours. Each preset answers all of them; we score the result.")
    judge = st.checkbox("⭐ Also grade with LLM-as-judge (slower, costs a little)")
    cols = st.columns(len(PRESETS))
    for col, (name, cfg) in zip(cols, PRESETS.items()):
        if col.button(f"Run: {name}"):
            with st.spinner(f"Running {name}..."):
                evals.run_eval(kb, cfg, name, judge=judge)
    runs = evals.load_runs()
    if runs:
        order = [n for n in PRESETS if n in runs]
        df = pd.DataFrame([{k: runs[n][k] for k in ["preset", "retrieval_hit", "answer_correct", "stale_rate", "leak_rate", "avg_seconds", "total_usd", "judge_avg", "mode"]} for n in order])
        st.dataframe(df, hide_index=True)
        st.caption("Higher is better: retrieval_hit, answer_correct.  Lower is better: stale_rate, leak_rate.")
        st.bar_chart(df.set_index("preset")[["retrieval_hit", "answer_correct", "stale_rate", "leak_rate"]])
        pick = st.selectbox("See every question for", order)
        rows = pd.DataFrame(runs[pick]["rows"])
        cols_show = [c for c in ["tag", "role", "q", "hit", "correct", "stale", "leak", "judge", "answer"] if c in rows.columns]
        st.dataframe(rows[cols_show], hide_index=True)
    else:
        st.info("No runs yet. Click a Run button above (start with Baseline).")

# ------------------------------------------------------------------ Ingestion
with tab_ing:
    st.subheader("1. See how a document is chunked")
    ids = [f"{d.id} ({d.status})" for d in kb.docs]
    sel = st.selectbox("Document", ids)
    doc = kb.docs[ids.index(sel)]
    a, b = st.columns(2)
    with a:
        st.markdown("**Fixed chunks (40 words)**")
        for c in chunk_docs([doc], "fixed", 40):
            st.code(c.text, language=None)
    with b:
        st.markdown("**Section chunks**")
        for c in chunk_docs([doc], "section"):
            st.code(c.text, language=None)

    st.subheader("2. Add new documents")
    st.caption(f"Sample files are in {UPLOAD_DIR}")
    files = st.file_uploader("Markdown files", type=["md", "txt"], accept_multiple_files=True)
    if files and st.button("Ingest files"):
        for f in files:
            d = parse_doc(f.read().decode("utf-8"), fallback_id=f.name.rsplit(".", 1)[0])
            d.path = f.name
            kb.add(d)
            if d.flagged:
                st.error(f"⚠️ {d.id}: scan found hidden-instruction patterns. It is added, but turn on 'Scan uploads' to quarantine it.")
            else:
                st.success(f"✅ {d.id}: added, scan clean.")
    st.dataframe(pd.DataFrame([dict(id=d.id, title=d.title, type=d.type, visible_to=", ".join(d.roles), version=d.version,
                                    status=d.status, scan="⚠️" if d.flagged else "ok") for d in kb.docs]),
                 hide_index=True)
